static void rect(uint16_t v[TTG_UI_H][TTG_UI_W],int x,int y,int w,int h,uint16_t c){
 for(int j=y;j<y+h;j++)for(int i=x;i<x+w;i++)if(i>=0&&i<TTG_UI_W&&j>=0&&j<TTG_UI_H)v[j][i]=c;
}
static void string(uint16_t v[TTG_UI_H][TTG_UI_W],int x,int y,const char *s,int k,uint16_t c){
 while(*s){unsigned t=0;
   for(unsigned i=0;cs[i];i++)if(cs[i]==*s){t=i;break;}
   for(int b=0;b<7;b++)for(int a=0;a<5;a++)if(f[t][a]&(1u<<b))rect(v,x+a*k,y+b*k,k,k,c);
   x+=6*k;s++;
 }
}
void ttg_ui_init(ttg_ui *u){
 memset(u,0,sizeof(*u));
 for(int a=0;a<6;a++){u->enabled[a]=1;for(int k=0;k<4;k++)u->values[a][k]=40+10*k;}
}
void ttg_ui_side(ttg_ui *u,int side){u->selected=(u->selected+(side>0?1:5))%6;u->parameter=0;u->editing=0;}
void ttg_ui_turn(ttg_ui *u,int d){
 if(u->editing){int t=u->values[u->selected][u->parameter]+d;
   u->values[u->selected][u->parameter]=t<0?0:t>100?100:t;
 }else{int t=u->parameter+d;u->parameter=t<0?0:t>=4?3:t;}
}
void ttg_ui_press(ttg_ui *u,int held){if(held){u->enabled[u->selected]^=1;u->editing=0;}else u->editing^=1;}
